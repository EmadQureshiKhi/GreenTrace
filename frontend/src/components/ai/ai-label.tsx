import { Sparkles } from 'lucide-react';
import { cn } from '@/lib/utils';

/** Marks content produced or reviewed by AI, with the model on hover. */
export function AiLabel({ model, text = 'AI', className }: { model?: string | null; text?: string; className?: string }) {
  return (
    <span
      title={model ? `Generated by ${model}` : undefined}
      className={cn(
        'inline-flex items-center gap-1 rounded-full bg-violet-100 px-2 py-0.5 text-xs font-medium text-violet-800 dark:bg-violet-950 dark:text-violet-200',
        className,
      )}
    >
      <Sparkles className="h-3 w-3" />
      {text}
    </span>
  );
}
